"""JWT issue/verify (Review Focus 3): forged, expired, alg=none and wrong-audience tokens are refused.

The gateway verifies tokens locally (Task 9), so `tokens.verify` is the whole authentication
decision: anything it accepts is a logged-in principal.
"""
from __future__ import annotations

import base64
import json

import jwt
import pytest

from app.security import tokens
from app.security.tokens import Principal, TokenError

SECRET = "unit-test-secret-0123456789abcdefghij"  # >= 32 bytes, as generated by experiments/env.ts
NOW = 1_800_000_000


@pytest.fixture(autouse=True)
def secret(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setenv("JWT_SECRET", SECRET)


def _b64(obj: dict) -> str:
    return base64.urlsafe_b64encode(json.dumps(obj).encode()).rstrip(b"=").decode()


def _claims(**overrides) -> dict:
    claims = {"sub": "s7", "role": "student", "student_id": "s7", "iss": tokens.ISSUER,
              "aud": tokens.AUDIENCE, "iat": NOW, "exp": NOW + tokens.TTL_S}
    claims.update(overrides)
    return claims


def _reason(token: str, now: int = NOW + 1) -> str:
    with pytest.raises(TokenError) as info:
        tokens.verify(token, now=now)
    return info.value.reason


def test_issue_then_verify_roundtrip() -> None:
    token = tokens.issue("s7", "student", "s7", now=NOW)
    assert tokens.verify(token, now=NOW + 1) == Principal(sub="s7", role="student", student_id="s7")
    staff = tokens.verify(tokens.issue("bursar", "staff", None, now=NOW), now=NOW + 1)
    assert staff == Principal(sub="bursar", role="staff", student_id=None)


def test_issued_token_claims() -> None:
    token = tokens.issue("bursar", "staff", None, now=NOW)
    header = jwt.get_unverified_header(token)
    claims = jwt.decode(token, options={"verify_signature": False})
    assert header["alg"] == "HS256"
    assert claims["iss"] == "ftu-auth" and claims["aud"] == "ftu-api"
    assert claims["exp"] - claims["iat"] == 900 == tokens.TTL_S  # short-lived: 15 minutes


def test_verify_rejects_expired() -> None:
    token = tokens.issue("s7", "student", "s7", now=NOW)
    assert tokens.verify(token, now=NOW + 899).sub == "s7"
    assert _reason(token, now=NOW + 900) == "expired"
    assert _reason(token, now=NOW + 3600) == "expired"


def test_verify_rejects_bad_signature() -> None:
    forged = jwt.encode(_claims(role="admin"), "attacker-secret-0123456789abcdefghij", algorithm="HS256")
    assert _reason(forged) == "bad_signature"
    # a valid token with one payload byte changed (privilege escalation attempt)
    header, payload, signature = tokens.issue("s7", "student", "s7", now=NOW).split(".")
    tampered = ".".join([header, _b64(_claims(role="admin")), signature])
    assert _reason(tampered) == "bad_signature"


def test_verify_rejects_alg_none() -> None:
    unsigned = f"{_b64({'alg': 'none', 'typ': 'JWT'})}.{_b64(_claims(role='admin'))}."
    assert _reason(unsigned) == "malformed"
    # alg=none with the real signature attached is refused too: only HS256 is accepted
    signature = tokens.issue("s7", "student", "s7", now=NOW).split(".")[2]
    assert _reason(f"{_b64({'alg': 'none', 'typ': 'JWT'})}.{_b64(_claims())}.{signature}") == "malformed"


def test_verify_rejects_other_algorithms() -> None:
    # HS512 with the right secret is still not HS256: the algorithm list is pinned
    token = jwt.encode(_claims(), SECRET, algorithm="HS512")
    assert _reason(token) == "malformed"


def test_verify_rejects_wrong_audience() -> None:
    token = jwt.encode(_claims(aud="some-other-api"), SECRET, algorithm="HS256")
    assert _reason(token) == "bad_audience"
    no_aud = _claims()
    del no_aud["aud"]
    assert _reason(jwt.encode(no_aud, SECRET, algorithm="HS256")) in ("bad_audience", "malformed")


def test_verify_rejects_wrong_issuer() -> None:
    assert _reason(jwt.encode(_claims(iss="someone-else"), SECRET, algorithm="HS256")) == "malformed"


@pytest.mark.parametrize("claims", [
    {"role": "superuser"},           # not a known role
    {"sub": ""},                     # empty subject
    {"student_id": None},            # a student token must name its student
    {"exp": None},                   # no expiry: never accepted
])
def test_verify_rejects_bad_claims(claims: dict) -> None:
    body = _claims(**claims)
    body = {k: v for k, v in body.items() if v is not None}
    assert _reason(jwt.encode(body, SECRET, algorithm="HS256")) == "malformed"


@pytest.mark.parametrize("garbage", ["", "abc", "a.b.c", "Bearer x.y.z", "\n" * 3, "x" * 10_000])
def test_verify_rejects_garbage(garbage: str) -> None:
    assert _reason(garbage) == "malformed"


def test_issue_and_verify_refuse_without_secret(monkeypatch: pytest.MonkeyPatch) -> None:
    token = tokens.issue("s7", "student", "s7", now=NOW)
    monkeypatch.delenv("JWT_SECRET")
    with pytest.raises(RuntimeError):
        tokens.issue("s7", "student", "s7", now=NOW)
    assert _reason(token) == "malformed"  # fail closed: no secret means nothing verifies
